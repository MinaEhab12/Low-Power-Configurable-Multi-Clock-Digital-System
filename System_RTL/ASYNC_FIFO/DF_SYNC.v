module DF_SYNC #(
    parameter BUS_WIDTH = 4   // Width of the data bus
)(
    ///////////////////////////////////////////////////////
    ///////////////// Input Signals ///////////////////////
    ///////////////////////////////////////////////////////
    input  wire                   i_clk,         // Clock
    input  wire                   i_rst_n,       // Active-low reset
    input  wire [BUS_WIDTH-1:0]   i_async_data,  // Asynchronous input data

    ///////////////////////////////////////////////////////
    //////////////// Output Signals ///////////////////////
    ///////////////////////////////////////////////////////
    output wire [BUS_WIDTH-1:0]   o_sync_data    // Synchronized output data
);

    ///////////////////////////////////////////////////////
    ////////////// Internal Registers /////////////////////
    ///////////////////////////////////////////////////////
    reg [BUS_WIDTH-1:0] sync_stage1;  // First stage flip-flop
    reg [BUS_WIDTH-1:0] sync_stage2;  // Second stage flip-flop

    ///////////////////////////////////////////////////////
    /////////////// Synchronizer Process //////////////////
    ///////////////////////////////////////////////////////
    always @(posedge i_clk or negedge i_rst_n) begin
        if (!i_rst_n) begin
            sync_stage1 <= 'b0;
            sync_stage2 <= 'b0;
        end 
        else begin
            sync_stage1 <= i_async_data;
            sync_stage2 <= sync_stage1;
        end
    end

    ///////////////////////////////////////////////////////
    ///////////////// Output Assignment ///////////////////
    ///////////////////////////////////////////////////////
    assign o_sync_data = sync_stage2;

endmodule
